// Numbers of `npm run perf:canvas`: the frame times of a card drag and how often the builder parts render during it.

export type RenderCounts = Record<string, number>;

export interface DragMeasurement {
  label: string;
  steps: number;
  /** `requestAnimationFrame` timestamps in ms, from the first move to the drop. */
  frameTimes: number[];
  renders: RenderCounts;
  rendersBefore: RenderCounts;
  visibleBefore: number;
  visibleDuring: number;
  visibleAfter: number;
  screenshot: string;
}

export const COUNTED_PARTS = ['BuilderScreen', 'SettingsPanel', 'StepList', 'StepCard'] as const;

/** Nearest-rank percentile; 0 for no values. The input is not changed. */
export function percentile(values: number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const rank = Math.max(1, Math.ceil((p / 100) * sorted.length));
  return sorted[Math.min(rank, sorted.length) - 1] as number;
}

export function frameGaps(times: number[]): number[] {
  const gaps: number[] = [];
  for (let i = 1; i < times.length; i++) gaps.push(Math.round((times[i] as number) - (times[i - 1] as number)));
  return gaps;
}

export interface DragSummary {
  frames: number;
  p95: number;
  max: number;
  added: RenderCounts;
  allVisible: boolean;
}

export function summarizeDrag(m: DragMeasurement): DragSummary {
  const gaps = frameGaps(m.frameTimes);
  const added: RenderCounts = {};
  for (const part of COUNTED_PARTS) added[part] = (m.renders[part] ?? 0) - (m.rendersBefore[part] ?? 0);
  return {
    frames: m.frameTimes.length,
    p95: percentile(gaps, 95),
    max: gaps.length ? Math.max(...gaps) : 0,
    added,
    allVisible: m.visibleBefore === m.steps && m.visibleDuring === m.steps && m.visibleAfter === m.steps,
  };
}

export function renderPerfReport(runs: DragMeasurement[], info: { generatedAt: string; moves: number }): string {
  const rows = runs.map((m) => {
    const s = summarizeDrag(m);
    return `| ${m.label} | ${m.steps} | ${s.frames} | ${s.p95} | ${s.max} | ${s.added.BuilderScreen} | ${s.added.SettingsPanel} | ${s.added.StepList} | ${s.added.StepCard} | ${s.allVisible ? 'yes' : `NO (${m.visibleBefore}/${m.visibleDuring}/${m.visibleAfter} of ${m.steps})`} |`;
  });
  return [
    '# Canvas drag measurements',
    '',
    `Generated by \`npm run perf:canvas\` on ${info.generatedAt}. Do not edit by hand: the script writes this file again on every run.`,
    '',
    `One card is dragged with the mouse in ${info.moves} moves in headless Chromium at 1440 x 900, on a production build with the render counters on (\`VITE_PERF_COUNTERS=true\`). Frame times are the gaps between \`requestAnimationFrame\` callbacks in ms. "Added renders" are the renders of each part during the drag only.`,
    '',
    '| Flow | Steps | Frames | p95 frame (ms) | Slowest frame (ms) | BuilderScreen | SettingsPanel | StepList | StepCard (all cards) | Every card visible (before / during / after) |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    'Screenshots at the middle of each drag are in `docs/canvas-perf/`.',
    '',
  ].join('\n');
}
