// `npm run perf:print` (task T9.1, not a gate): writes a report of 5,000, 20,000 and 50,000 rows by 12 columns with ExcelJS the way a
// print layout does, in headless Chromium, and records the time, the memory and the size of the file in docs/PRINT_PERF.md.
// It also records the size of the main file of the app, which ExcelJS must not make larger (it is a separate file of the build).
// Usage: npm run perf:print
import { readdir, rm, stat, writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { build, preview } from 'vite';

const PORT = 4180;
const REPORT = 'docs/PRINT_PERF.md';
const SIZES = [5000, 20000, 50000];

interface Row {
  rows: number;
  ms: number;
  bytes: number;
  peakHeapMb: number;
  loadMs: number;
}

const kb = (n: number): string => `${(n / 1024).toFixed(0)} KB`;
const mb = (n: number): string => `${(n / 1048576).toFixed(1)} MB`;

async function sizeOf(dir: string, re: RegExp): Promise<{ name: string; bytes: number }[]> {
  const out: { name: string; bytes: number }[] = [];
  for (const f of await readdir(dir)) if (re.test(f)) out.push({ name: f, bytes: (await stat(`${dir}/${f}`)).size });
  return out;
}

async function main(): Promise<void> {
  await build({ configFile: 'vite.acceptance.config.ts', logLevel: 'warn', build: { outDir: 'dist-perf-print', emptyOutDir: true } });
  const server = await preview({ configFile: 'vite.acceptance.config.ts', build: { outDir: 'dist-perf-print' }, preview: { port: PORT, strictPort: true } });
  const browser = await chromium.launch({ args: ['--enable-precise-memory-info'] });
  const rows: Row[] = [];
  try {
    for (const n of SIZES) {
      // A fresh page for each size, so that the memory of one run does not count in the next.
      const page = await browser.newPage();
      await page.goto(`http://localhost:${PORT}/acceptance/index.html`);
      await page.waitForFunction(() => typeof window.printProbe === 'function');
      const r = await page.evaluate((count) => window.printProbe(count), n);
      rows.push(r);
      console.log(`${n} rows: ${r.ms.toFixed(0)} ms, ${mb(r.bytes)}, peak heap ${r.peakHeapMb.toFixed(0)} MB`);
      await page.close();
    }
  } finally {
    await browser.close();
    await new Promise<void>((resolve) => server.httpServer.close(() => resolve()));
  }
  const assets = await sizeOf('dist-perf-print/assets', /\.js$/);
  const excel = assets.filter((a) => /exceljs|excel/i.test(a.name));
  const biggest = [...assets].sort((a, b) => b.bytes - a.bytes).slice(0, 4);
  const table = rows.map((r) => `| ${r.rows.toLocaleString('en-US')} | ${(r.ms / 1000).toFixed(1)} | ${r.peakHeapMb.toFixed(0)} | ${mb(r.bytes)} |`).join('\n');
  const text = `# Print layout measurements

Generated by \`npm run perf:print\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: the script writes this file again on every run.

A report of N rows by 12 columns (text, numbers with a thousands format, dates, a long text that wraps) is written by the real writer of
the app (\`buildPrintWorkbook\`, with ExcelJS) in headless Chromium, on a production build, with everything a print layout adds: a thin border on
every cell, a bold header row on a fill, two header lines, the page set to fit one page wide, a repeated header row, no gridlines, the signature
block with its page-break check, and the footer. The time is from the first row to the buffer of the file (the load of ExcelJS is
not in it). The memory is the largest used JS heap seen while writing (sampled every 20 ms). The first load of the ExcelJS file took
${rows[0]?.loadMs.toFixed(0)} ms on this machine.

| Rows | Time (s) | Peak JS heap (MB) | File |
| --- | --- | --- | --- |
${table}

The row limit of a print layout is 20,000 (SPEC 16.1 item 7) unless the time or the memory above is too high for a person who waits for the
file on a normal office computer; the numbers of 20,000 rows are the ones to read.

## The size of the build

ExcelJS is loaded only through a dynamic import (\`src/engine/output/print/load-exceljs.ts\`), so it is a separate file of the build and the main file does not grow.
The largest JavaScript files of the build of this probe:

${biggest.map((a) => `- \`${a.name}\`: ${kb(a.bytes)}`).join('\n')}
${excel.length > 0 ? `\nThe ExcelJS file: ${excel.map((a) => `\`${a.name}\` ${kb(a.bytes)}`).join(', ')}.` : ''}
`;
  await writeFile(REPORT, text);
  await rm('dist-perf-print', { recursive: true, force: true });
  console.log(`Wrote ${REPORT}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
